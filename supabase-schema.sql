-- Ordo Noctis: Erweiterung des bestehenden Gemeinschafts-Wikis
create table if not exists public.wiki_articles (
 id uuid primary key, title text, category text default 'Allgemein', description text default '', content text default '',
 title_de text, title_en text, description_de text default '', description_en text default '', content_de text default '', content_en text default '',
 created_at timestamptz default now(), updated_at timestamptz default now()
);
alter table public.wiki_articles add column if not exists title_de text;
alter table public.wiki_articles add column if not exists title_en text;
alter table public.wiki_articles add column if not exists description_de text default '';
alter table public.wiki_articles add column if not exists description_en text default '';
alter table public.wiki_articles add column if not exists content_de text default '';
alter table public.wiki_articles add column if not exists content_en text default '';
update public.wiki_articles set title_de=coalesce(title_de,title),description_de=coalesce(description_de,description,''),content_de=coalesce(content_de,content,'') where title_de is null;
create table if not exists public.wiki_settings(id integer primary key check(id=1),whatsapp_url text default '');
insert into public.wiki_settings(id,whatsapp_url) values(1,'') on conflict(id) do nothing;
create table if not exists public.page_visits(id bigint generated by default as identity primary key,visited_at timestamptz default now());
create table if not exists public.membership_requests(id uuid primary key default gen_random_uuid(),name text not null,phone text not null,reason text not null,status text not null default 'pending' check(status in('pending','accepted','rejected')),created_at timestamptz default now(),reviewed_at timestamptz);
create table if not exists public.admin_login_logs(id bigint generated by default as identity primary key,event text not null,details text,created_at timestamptz default now());
create table if not exists public.admin_activity_logs(id bigint generated by default as identity primary key,event text not null,details text,created_at timestamptz default now());
alter table public.wiki_articles enable row level security;
alter table public.wiki_settings enable row level security;
alter table public.page_visits enable row level security;
alter table public.membership_requests enable row level security;
alter table public.admin_login_logs enable row level security;
alter table public.admin_activity_logs enable row level security;
drop policy if exists "Public can read articles" on public.wiki_articles;
create policy "Public can read articles" on public.wiki_articles for select to anon,authenticated using(true);
drop policy if exists "Public can read settings" on public.wiki_settings;
create policy "Public can read settings" on public.wiki_settings for select to anon,authenticated using(true);
